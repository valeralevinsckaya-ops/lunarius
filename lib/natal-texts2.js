const DIGNITY = {
  sun: { dom: ['leo'], exalt: ['aries'], detr: ['aquarius'], fall: ['libra'] },
  moon: { dom: ['cancer'], exalt: ['taurus'], detr: ['capricorn'], fall: ['scorpio'] },
  mercury: { dom: ['gemini', 'virgo'], exalt: [], detr: ['sagittarius', 'pisces'], fall: [] },
  venus: { dom: ['taurus', 'libra'], exalt: ['pisces'], detr: ['scorpio', 'aries'], fall: ['virgo'] },
  mars: { dom: ['aries', 'scorpio'], exalt: ['capricorn'], detr: ['libra', 'taurus'], fall: ['cancer'] },
  jupiter: { dom: ['sagittarius', 'pisces'], exalt: ['cancer'], detr: ['gemini', 'virgo'], fall: ['capricorn'] },
  saturn: { dom: ['capricorn', 'aquarius'], exalt: ['libra'], detr: ['cancer', 'leo'], fall: ['aries'] },
};
const DIGNITY_TEXT = {
  dom: (p) => `${p} в обители, то есть в своем знаке: планета работает в полную силу и естественно.`,
  exalt: (p) => `${p} в экзальтации: знак усиливает лучшие качества планеты.`,
  detr: (p) => `${p} в изгнании: знак противоположен родному, поэтому качества планеты проявляются непривычно и требуют осознанности.`,
  fall: (p) => `${p} в падении: планете неуютно в этом знаке, и ее сила раскрывается с опытом и усилием.`,
};
function dignity(planet, sign, planetRu, signText) {
  const d = DIGNITY[planet]; if (!d) return null;
  for (const k of ['dom', 'exalt', 'detr', 'fall']) {
    if (d[k].includes(sign)) {
      if ((k === 'dom' && /у себя дома/.test(signText)) || (k === 'exalt' && /экзальтац/.test(signText))) return null;
      return DIGNITY_TEXT[k](planetRu);
    }
  }
  return null;
}

